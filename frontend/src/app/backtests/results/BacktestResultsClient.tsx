"use client";

import Link from "next/link";
import { FileDown, Printer, Play } from "lucide-react";
import type { PersistedBacktest } from "@/features/backtest/types";
import { Table, TableBody, TableCell, TableHead, TableHeader, TableRow } from "@/components/ui/table";
import PerformanceChart from "@/components/charts/PerformanceChart";
import { exportBacktestCSV, exportBacktestPDF } from "@/lib/exportUtils";

function formatNumber(value: number, decimals = 2) {
  return value.toFixed(decimals);
}

function formatDecimalPercent(value: number) {
  return `${(value * 100).toFixed(2)}%`;
}

function Metric({ title, value, positive }: { title: string; value: string | number; positive?: boolean }) {
  return (
    <div className="rounded border border-zinc-200 bg-white p-4 space-y-1">
      <p className="text-[10px] font-mono font-medium uppercase tracking-wider text-zinc-500">{title}</p>
      <p className={`font-mono text-xl font-bold ${positive === true ? 'text-emerald-600' : positive === false ? 'text-red-600' : 'text-zinc-900'}`}>
        {value}
      </p>
    </div>
  );
}

export default function BacktestResultsClient({ result }: { result: PersistedBacktest }) {
  const performanceData = result.equityCurve ?? [];

  return (
    <div className="space-y-8 p-4 md:p-8 max-w-7xl mx-auto">
      {/* Header with Export Controls */}
      <div className="flex flex-col gap-4 sm:flex-row sm:items-center sm:justify-between border-b border-zinc-200 pb-5">
        <div>
          <div className="flex items-center gap-3">
            <h1 className="text-2xl font-bold font-mono tracking-tight text-zinc-900">
              BACKTEST_EXECUTION_RESULTS
            </h1>
            <span className="px-2.5 py-0.5 rounded border border-zinc-200 bg-zinc-50 text-xs font-mono font-semibold text-zinc-800">
              {result.strategy}
            </span>
          </div>
          <p className="mt-1 text-xs text-zinc-600">
            Institutional performance analysis and trade logs generated by compiled C++ quant engine.
          </p>
        </div>

        <div className="flex flex-wrap items-center gap-2.5">
          <button
            type="button"
            onClick={() => exportBacktestCSV(result)}
            className="inline-flex h-9 items-center gap-1.5 rounded border border-zinc-200 bg-white px-3.5 text-xs font-mono font-medium text-zinc-900 transition hover:bg-zinc-50"
          >
            <FileDown className="size-3.5 text-zinc-600" />
            EXPORT_CSV
          </button>

          <button
            type="button"
            onClick={() => exportBacktestPDF(result)}
            className="inline-flex h-9 items-center gap-1.5 rounded border border-zinc-200 bg-white px-3.5 text-xs font-mono font-medium text-zinc-900 transition hover:bg-zinc-50"
          >
            <Printer className="size-3.5 text-zinc-600" />
            EXPORT_PDF
          </button>

          <Link
            href="/backtests/new"
            className="inline-flex h-9 items-center gap-1.5 rounded bg-zinc-950 px-4 text-xs font-mono font-medium text-white transition hover:bg-zinc-800"
          >
            <Play className="size-3.5 fill-current" />
            NEW_BACKTEST
          </Link>
        </div>
      </div>

      {/* Performance Summary */}
      <section className="space-y-3">
        <h2 className="text-[10px] font-mono font-bold uppercase tracking-wider text-zinc-500">PERFORMANCE_SUMMARY</h2>
        <div className="grid gap-3 grid-cols-2 md:grid-cols-3 lg:grid-cols-6">
          <Metric title="Initial Capital" value={`$${formatNumber(result.initialCapital)}`} />
          <Metric title="Final Equity" value={`$${formatNumber(result.finalEquity)}`} />
          <Metric title="Net Profit" value={`${result.netProfit >= 0 ? '+' : ''}$${formatNumber(result.netProfit)}`} positive={result.netProfit >= 0} />
          <Metric title="Total Return" value={`${result.totalReturnPercent >= 0 ? '+' : ''}${formatNumber(result.totalReturnPercent)}%`} positive={result.totalReturnPercent >= 0} />
          <Metric title="Sharpe Ratio" value={formatNumber(result.sharpeRatio)} />
          <Metric title="Max Drawdown" value={`-${formatNumber(result.maximumDrawdown)}%`} positive={false} />
        </div>
      </section>

      {/* Equity Curve */}
      <section className="rounded border border-zinc-200 bg-white p-6 space-y-4">
        <div className="flex items-center justify-between">
          <h2 className="text-[10px] font-mono font-bold uppercase tracking-wider text-zinc-500">EQUITY_CURVE_TRAJECTORY</h2>
          <span className="text-xs font-mono text-zinc-400">{performanceData.length} data points</span>
        </div>
        <div className="h-[320px]">
          <PerformanceChart data={performanceData} />
        </div>
      </section>

      {/* Trade Statistics & Risk Grid */}
      <div className="grid grid-cols-1 md:grid-cols-2 gap-6">
        <section className="rounded border border-zinc-200 bg-white p-6 space-y-4">
          <h2 className="text-[10px] font-mono font-bold uppercase tracking-wider text-zinc-500">TRADE_STATISTICS</h2>
          <div className="grid grid-cols-2 gap-3">
            <Metric title="Total Trades" value={result.totalTrades} />
            <Metric title="Win Rate" value={`${formatNumber(result.winRatePercent)}%`} positive={result.winRatePercent >= 50} />
            <Metric title="Winning Trades" value={result.winningTrades} positive={true} />
            <Metric title="Losing Trades" value={result.losingTrades} positive={false} />
          </div>
        </section>

        <section className="rounded border border-zinc-200 bg-white p-6 space-y-4">
          <h2 className="text-[10px] font-mono font-bold uppercase tracking-wider text-zinc-500">RISK_AND_EXPECTATIONS</h2>
          <div className="grid grid-cols-2 gap-3">
            <Metric title="Profit Factor" value={formatNumber(result.profitFactor)} />
            <Metric title="Expectancy" value={formatNumber(result.expectancy)} />
            <Metric title="Annualized Return" value={formatDecimalPercent(result.annualizedReturn)} />
            <Metric title="Annualized Volatility" value={formatDecimalPercent(result.annualizedVolatility)} />
          </div>
        </section>
      </div>

      {/* Trade History Table */}
      <section className="rounded border border-zinc-200 bg-white p-6 space-y-4">
        <div className="flex items-center justify-between">
          <h2 className="text-[10px] font-mono font-bold uppercase tracking-wider text-zinc-500">TRADE_EXECUTION_LEDGER</h2>
          <span className="text-xs font-mono text-zinc-400">{result.trades.length} recorded orders</span>
        </div>

        <div className="overflow-x-auto rounded border border-zinc-200">
          <Table>
            <TableHeader className="bg-zinc-50/80">
              <TableRow className="border-zinc-200">
                <TableHead className="text-xs font-mono font-bold text-zinc-600">Timestamp</TableHead>
                <TableHead className="text-xs font-mono font-bold text-zinc-600">Side</TableHead>
                <TableHead className="text-xs font-mono font-bold text-zinc-600">Quantity</TableHead>
                <TableHead className="text-xs font-mono font-bold text-zinc-600">Execution Price</TableHead>
                <TableHead className="text-xs font-mono font-bold text-zinc-600">Commission</TableHead>
                <TableHead className="text-xs font-mono font-bold text-zinc-600">Cash Flow</TableHead>
              </TableRow>
            </TableHeader>
            <TableBody className="divide-y divide-zinc-200">
              {result.trades.length === 0 ? (
                <TableRow>
                  <TableCell colSpan={6} className="text-center py-8 text-xs font-mono text-zinc-400">
                    NO_TRADE_EXECUTIONS_RECORDED
                  </TableCell>
                </TableRow>
              ) : (
                result.trades.map((trade, index) => (
                  <TableRow key={`${trade.timestamp}-${index}`} className="hover:bg-zinc-50/60 font-mono text-xs">
                    <TableCell className="text-zinc-600">{trade.timestamp.replace("T", " ").slice(0, 16)}</TableCell>
                    <TableCell>
                      <span className={`inline-flex items-center rounded border px-2 py-0.5 text-[10px] font-bold uppercase tracking-wider ${
                        trade.side === "BUY"
                          ? "border-emerald-200 bg-emerald-50 text-emerald-700"
                          : "border-red-200 bg-red-50 text-red-700"
                      }`}>
                        {trade.side}
                      </span>
                    </TableCell>
                    <TableCell className="text-zinc-700">{trade.quantity}</TableCell>
                    <TableCell className="text-zinc-700">${formatNumber(trade.executionPrice)}</TableCell>
                    <TableCell className="text-zinc-400">${formatNumber(trade.commission)}</TableCell>
                    <TableCell className={trade.cashFlow >= 0 ? "text-emerald-600 font-semibold" : "text-red-600 font-semibold"}>
                      {trade.cashFlow >= 0 ? "+" : ""}${formatNumber(trade.cashFlow)}
                    </TableCell>
                  </TableRow>
                ))
              )}
            </TableBody>
          </Table>
        </div>
      </section>
    </div>
  );
}
